export function makeDungeonBiome(theme, modifier = null) {
  const fogFactor = theme.fogFactor * (modifier?.fogScale || 1);
  return {
    id: `dungeon:${theme.id}`,
    label: theme.label,
    phase: 'SUBTERRANEAN',
    groundKind: 'city',
    dressing: 'city',
    weather: 'clear',
    entryKicker: theme.kicker,
    entryText: theme.entryText,
    fog: {
      color: theme.fog,
      density: theme.fogDensity,
      background: theme.background,
    },
    sun: { color: theme.light, intensity: 0.4 },
    hemi: { sky: theme.trim, ground: theme.floor, intensity: 0.52 },
    fill: { color: theme.accent, intensity: 0.24 },
    atmosphere: { rain: 0, wind: 0.04, snow: 0, dust: 0, lightning: false },
    roadTint: 0xffffff,
    vehicleTint: 0xffffff,
    palette: {
      rifleman: { uniform: 0x4f5a48, uniformDark: 0x30382c, vest: 0x3b4435, accent: theme.accent, helmet: 0x343b2d, headgear: 'helmet' },
      officer: { uniform: 0x3b4538, uniformDark: 0x242b22, vest: 0x2d352a, accent: theme.accent, helmet: 0x2a3024, headgear: 'beret' },
      mortar: { uniform: 0x4a5341, uniformDark: 0x343b2e, vest: 0x333b2e, accent: theme.trim, helmet: 0x3b4334, headgear: 'helmet' },
      heavy: { uniform: 0x384133, uniformDark: 0x20261e, vest: 0x2a3227, accent: theme.accent, helmet: 0x2d3429, headgear: 'helmet' },
    },
    dungeonFogFactor: clamp01(fogFactor),
  };
}

function clamp01(value) {
  return Math.max(0, Math.min(1, value));
}
